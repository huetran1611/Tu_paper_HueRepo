"""Generate 39 thin workflow_dispatch entry points; shared worker has one matrix job."""
import argparse
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
TEMPLATE='''# Generated by scripts/generate_paper_tables_678_workflows.py.
# @COUNT@ solver jobs; no build, planning or report runner in this workflow.
name: Paper T678 batch @LABEL@ - @COUNT@ processes
run-name: T678 batch @LABEL@ setup-${{ inputs.setup_run_id }}${{ inputs.reservation && format(' slots-{0}', inputs.reservation) || '' }}
on:
  workflow_dispatch:
    inputs:
      setup_run_id:
        description: 'Run ID of the version-2 Tables 6-7-8 setup'
        type: string
        required: true
      slots:
        description: 'JSON array of task slots; setup sends only missing slots when resuming'
        type: string
        default: '@SLOTS@'
      reservation:
        description: 'Internal coordinator reservation; leave empty for manual runs'
        type: string
        default: ''
permissions:
  contents: read
  actions: read
jobs:
  solve:
    uses: ./.github/workflows/paper-tables-678-worker.yml
    with:
      setup_run_id: ${{ inputs.setup_run_id }}
      batch: @BATCH@
      slots: ${{ inputs.slots }}
'''


def generated():
    for number in range(1,40):
        count=250 if number<39 else 100
        text=TEMPLATE.replace("@COUNT@",str(count)).replace("@LABEL@",f"{number:02d}").replace("@BATCH@",str(number)).replace("@SLOTS@",json.dumps(list(range(count)),separators=(",",":")))
        yield ROOT/f".github/workflows/paper-tables-678-batch-{number:02d}.yml",text


if __name__=="__main__":
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument("--check",action="store_true");args=parser.parse_args()
    for path,text in generated():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8")!=text: raise SystemExit("Regenerate workflow: "+str(path))
        else: path.write_text(text,encoding="utf-8",newline="\n")
    print("PASS: 38 x 250 + 1 x 100 = 9600 independent solver jobs")
